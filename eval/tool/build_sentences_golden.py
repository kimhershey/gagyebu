def main():
    out = pathlib.Path(__file__).resolve().parents[1] / "golden" / "sentences.jsonl"
    lines = []
    for i, (text, date, amount, direction, party) in enumerate(CASES, start=1):
        row = {
            "id": f"sentence_{i:03d}",
            "today": TODAY,
            "text": text,
            "expect": {"date": date, "amount": amount, "direction": direction},
        }
        if party is not None:
            row["counterparty_contains"] = party
        lines.append(json.dumps(row, ensure_ascii=False))
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines)}건 → {out}")


if __name__ == "__main__":
    main()
