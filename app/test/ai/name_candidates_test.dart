import 'package:flutter_test/flutter_test.dart';
import 'package:gagyebu/ai/text/name_candidates.dart';
import 'package:gagyebu/core/local_date.dart';

void main() {
  final today = LocalDate(2026, 11, 17);
  List<String> find(String text) => findNameCandidates(text, today);

  group('결제 문자: 형식 낱말을 지우고 남은 말', () {
    test('카드 승인', () {
      expect(
        find('KB국민카드1234승인\n홍*동님\n129,857원 일시불\n02/08 22:39\n마켓컬리\n누적800,000원'),
        ['마켓컬리'],
      );
      expect(
        find('신한카드(1234)승인 홍*동 2,400원(일시불)02/23 16:56 세븐일레븐영 누적1,427,265원'),
        ['세븐일레븐영'],
      );
      expect(find('삼성1234취소 홍*동\n-4,020원 일시불\n10/09 19:41 쿠팡\n누적1,100,000원'), [
        '쿠팡',
      ]);
    });

    test('이름에 공백이 있으면 한 후보로 묶는다', () {
      expect(
        find(
          '[카카오뱅크] 홍*동(1234) 12/11 15:42 출금 7,250원 세븐일레븐 가평목동 잔액 4,123,123원',
        ),
        ['세븐일레븐 가평목동'],
      );
    });

    test('은행 입출금', () {
      expect(
        find(
          '[KB]7/10 16:40\n123456****7890\n홍길동\n1,000,000 입금\n잔액 50,000\n1644-9999',
        ),
        ['홍길동'],
      );
      expect(find('우리 06/20 11:20 *123456 입금 472원 예금결산 잔액 1,199,234원'), [
        '예금결산',
      ]);
      expect(
        find(
          '하나,09/10 11:17 123******45607 출금13,958원 0908_GOOGLE*i 잔액669,942원',
        ),
        ['0908_GOOGLE*i'],
      );
      expect(
        find('농협 출금701,000원 08/22 22:35 352-****-0000-00 한패스오픈뱅 잔액4,308,001원'),
        ['한패스오픈뱅'],
      );
    });

    test('명의자와 항목 이름은 후보가 아니다', () {
      expect(
        find(
          '부산BC(1234)\n12,300원 사용\n개인\n홍길동님\n일시불 04/24 13:45\n총누적\n100,000원\n스타벅스',
        ),
        ['스타벅스'],
      );
      expect(
        find(
          '금액 12,300원\n카드 하나1*2*\n손님명 홍*동\n거래종류 신용\n거래구분 일시불\n'
          '사용처 쿠팡(쿠페이)\n거래시간 10/15 09:05\n누적금액 300,000원',
        ),
        ['쿠팡(쿠페이)'],
      );
    });
  });

  group('문장 입력: 묶음과 낱말을 함께 준다', () {
    test('상대와 내용을 나눠 고를 수 있다', () {
      expect(find('어제 점심 김밥천국 8천원 카드로'), ['점심 김밥천국', '점심', '김밥천국']);
      expect(find('오늘 스타벅스 아메리카노 4500원'), ['스타벅스 아메리카노', '스타벅스', '아메리카노']);
    });
    test('조사를 뗀다', () {
      expect(find('3일 전 쿠팡에서 생수 2박스 18,900원'), contains('쿠팡'));
      expect(find('엄마한테 용돈 10만원 받음'), containsAll(['엄마', '용돈']));
    });
    test('날짜 · 금액 · 결제수단은 후보가 아니다', () {
      expect(find('지난주 금요일 회식 3만 5천원'), ['회식']);
      expect(find('주차비 3천원 현금'), ['주차비']);
      expect(find('점심 12000'), ['점심']);
    });
  });

  group('숫자가 붙은 이름', () {
    test('이름에 든 숫자는 금액으로 잘라 내지 않는다', () {
      expect(find('이마트24 4,800원'), ['이마트24']);
      expect(find('11번가 23,000원 결제'), ['11번가']);
      expect(find('GS25 편의점 3,500원'), contains('GS25'));
    });
    test('금액이 이름에 붙어 있으면 이름만 남긴다', () {
      expect(find('스타벅스강남점12,000원'), ['스타벅스강남점']);
    });
  });

  test('계좌 별명과 결제 방식은 이름이 아니다', () {
    expect(
      find('케이뱅크\n입금 3,000,000원\n대출실행 ( 원금 )  | 생활통장(0000)\n잔액 3,109,662원'),
      ['대출실행 (원금)'],
    );
    expect(find('133,500원 결제\n하나카드 | 비비큐 강동밀레니얼점(일시불)'), ['비비큐 강동밀레니얼점']);
    expect(find('출금\n1,000원 홍길동 입출금(0000)\n11.09 16:41'), ['홍길동']);
    expect(find('입금\n10/12 14:53 1\n계좌 123456789***0\n내용 당근143\n잔액 500,000'), [
      '당근143',
    ]);
  });

  group('금융사가 보낸 글인지', () {
    test('거래 낱말, 시각, 가린 글자, 머리말, 카드 끝자리로 알아본다', () {
      for (final text in [
        '우체국 11/10 13:45 출금 55,000원 한국전력공사 잔액 812,300원',
        '네이버페이 결제완료 23,900원 무신사스토어 11.12 21:05',
        'Approved KRW 32,000 at COUPANG 11/08 20:15 Card *1234',
        '[BC카드] 취소 15,800원 11/11 교보문고 광화문점',
        '티머니 충전 30,000원 하늘카드(1234)',
        '신협\n출금 12,000원',
      ]) {
        expect(looksLikeMessage(text), isTrue, reason: text);
      }
    });
    test('사람이 쓴 문장은 아니다', () {
      for (final text in [
        '어제 점심 김밥천국 8천원 카드로',
        '11/2 전기요금 42,180원 납부',
        '지난주 금요일 회식 3만 5천원',
        '엄마한테 용돈 10만원 받음',
      ]) {
        expect(looksLikeMessage(text), isFalse, reason: text);
      }
    });
  });

  test('여러 줄이면 문자로 보고 묶음만 준다', () {
    expect(find('카카오페이 결제 완료\n12,900원\n올리브영 온라인몰'), ['카카오페이', '올리브영 온라인몰']);
  });

  test('남는 말이 없으면 빈 목록', () {
    expect(find('[롯데카드]11/16출금예정2,668,841원'), isEmpty);
    expect(find('12,000원'), isEmpty);
  });
}
