/// 상대방 이름과 문장의 낱말로 분류를 짐작하는 기본 사전.
///
/// LLM이 없는 기기(웹 앱, 저사양 폰)와 모델을 내려받기 전의 기본값으로 쓴다.
/// 우선순위는 사용자가 고친 분류 규칙(category_rules)이 가장 높고, 이 사전은 그다음이다.
/// 분류 이름은 기본 분류(`domain/default_seed.dart`)와 같아야 한다.
library;

import '../parsed_transaction.dart';

/// [text]에 맞는 기본 분류 이름. 짐작할 수 없으면 null.
///
/// 여러 낱말이 맞으면 가장 긴 낱말을 따른다('쿠팡이츠'는 '쿠팡'보다 먼저).
String? suggestCategoryName(String text, Direction direction) {
  final haystack = text.toLowerCase();
  final table = direction == Direction.incoming ? _income : _expense;

  String? best;
  var bestLength = 0;
  table.forEach((category, keywords) {
    for (final keyword in keywords) {
      if (keyword.length > bestLength && haystack.contains(keyword)) {
        best = category;
        bestLength = keyword.length;
      }
    }
  });
  return best;
}

